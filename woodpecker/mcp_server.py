"""MCP tools for agents: read, explain, and edit designs. The viewer reloads on every write."""
from __future__ import annotations

from typing import Any

from mcp.server.mcpserver import MCPServer

from . import catalog, cutlist, ikea, magpie, render, store
from .model import EPS, Design, DesignError
from .server import format_cutlist

INSTRUCTIONS = """\
Woodpecker is a woodworking / garage-building design tool. A design is a JSON file of
parametric parts; the human watches it in a 3D viewer that reloads on every change you make.

Every design has a Magpie page (when publishing is on): drawings from 5 angles, shopping
list, cut list, parameters and the tip check. It refreshes about 20 s after the design stops
changing; call wp_publish to refresh it at once and get its link, e.g. after a round of
edits or when the human asks for the page, pictures, materials or cut list. To start a
design from scratch, wp_create_design (no copy_from), then add materials and parts.

Model rules:
- Lengths in millimetres, angles in degrees. Axes: x = width (left->right), y = depth
  (front->back, front is y=0), z = up (floor is z=0).
- A part is a box with `size` [x, y, z] built from its local origin, placed so that origin
  sits at `at`. Values may be expressions over params ("base_w - 2 * ply"; sin/cos/tan/atan
  take degrees). Put anything the human might resize in a param.
- `shape: "gusset"` is a right-triangle knee brace; `leg` = side of the vertical leg
  (front/back/left/right), the horizontal leg is at the bottom.
- Round and shaped parts: `shape: "cylinder"` + `axis` (x|y|z, default z) fills `size` (round
  legs, dowels, posts, round tabletops: [d, d, length] along z); `shape: "sphere"` fills
  `size` (balls, finials); `shape: "prism"` + `axis` + `profile` [[u, v], ...] (a CONVEX
  outline in the other two axes, in order: x -> (y, z), y -> (x, z), z -> (x, y)) + `length`
  (brackets, chamfered blocks; split concave outlines into convex pieces). Volumes and
  weights use the true shape; the cut list marks them round / ball / profile.
- Cars and other things to check fit against are catalog items with `"reference": true`
  (vw-multivan-t61-2021, vw-golf-alltrack-2017): drawn solid, never in the cut list.
- `rotate`: {"axis": "x|y|z", "deg": ...} or a list of them, about world-aligned axes
  through the local origin (`at`), applied in order. Rotation about y by -30 tilts a
  board lying along +x up by 30 degrees. `at` is then NOT the bounding-box minimum.
- `ends`: {"start": deg, "end": deg} angled end cuts on a board lying along local x,
  tilting in the local x-z plane; positive = top edge shorter than the bottom at that end.
  For a board rising along +x (rotate y by -p), vertical (plumb) cuts are start = p and
  end = -p. The greenhouse design is a worked example (rafters, birdsmouth, ridge).
- `repeat`: {"count": n, "step": [dx, dy, dz]} or {"count": n, "axis": "y", "spacing": s}
  makes copies id[0]..id[n-1]. `mirror`: {"axis": "x", "about": v} adds mirrored copies
  (id~m). Joints may name the spec id to mean every copy.
- `component`: a catalog id (wp_catalog_search) instead of material/size: a bought product
  (IKEA KALLAX, BILLY, ...) drawn as its panels with ids like kallax/top. Its `at` is the
  product's min corner (x = width, y = depth, z = up) and it may be rotated about z.
  Respect the catalog's `construction` notes (honeycomb panels do not hold screws) and
  its published load limits. Never guess catalog numbers. For IKEA, use wp_ikea_search
  (live search of ikea.com) and wp_ikea_import (reads the product page and saves it to the
  catalog). For other makers, wp_catalog_add with numbers from the maker's page only, and
  list anything not published in `assumed`. Tell the human what an import had to assume.
- `cutouts`: [{"label", "at", "size"}] boxes cut from the part (local coords). A joint
  with `cut_into: [host ids]` cuts the joint's other parts out of the hosts (through-
  mortise, dado, birdsmouth notch). The viewer shows the holes; the cut list notes them.
- Materials may carry a `color` ("#rrggbb"); reference materials (site, cars, boundaries) use
  it to stay readable. A design with `"anchored": "<why>"` (carports, sheds, anything on
  footings) skips the tip check and shows that text instead.
- A design may set `"magpie_project": <id>` to put its Magpie page in another project
  (the house model `house` goes to House > Digital Twin). The house is generated by
  scripts/house_model.py from the traced plans: change the script and re-run it rather than
  editing that design with the tools, or the next run overwrites your edits.
- Every part needs a plain-English `role`: what it does structurally. That is what you
  read back when the human asks "explain this". Add `notes` for build tips.
- Materials have a kind: sheet (plywood; thinnest side must equal thickness), lumber
  (two smallest sides must equal section), hardware (bought, counted in the hardware
  list), reference (shown but not built, e.g. the TV; give mass_kg for the tip check).
  Optional price_eur (+ price_source) on materials and hardware feeds the cost estimate;
  only use prices you looked up, with the source.
- Parts may only overlap if a joint lists both of them. Joints also carry the fasteners,
  which is how a bracket or connection gets explained.

Working loop:
1. "this" / "the selected part" means wp_get_selection. Use wp_explain_part to explain it.
2. Edit with the smallest tool (wp_set_param before wp_update_part before rewriting).
3. After edits, run wp_check: fix new warnings (overlaps, wrong stock sizes, floating
   parts) and report tip-stability changes when the shape or weight moved.
4. wp_cut_list gives the parts list, stock to buy (with sheet layouts), bought items,
   hardware and cost.
5. wp_undo reverts the last write if the human does not like a change.
Do not edit design files by hand while the viewer is open; use the tools (they validate
and keep undo history).
"""

mcp = MCPServer("woodpecker", instructions=INSTRUCTIONS)


def _summary(d: Design) -> dict:
    st = cutlist.stability(d)
    return {
        "design": d.name,
        "issues": d.issues,
        "overall_mm": d.bounds(include_reference=False)["size"],
        "parts": len(d.parts),
        "tip_weakest": {"direction": st.get("weakest"),
                        **(st.get("tip", {}).get(st.get("weakest"), {}))} if st.get("tip") else None,
    }


def _touching(d: Design, part_id: str) -> list[dict]:
    a = d.part(part_id)
    out = []
    for b in d.parts:
        if b.id == a.id:
            continue
        gaps = [max(a.at[k], b.at[k]) - min(a.max[k], b.max[k]) for k in range(3)]
        if all(g <= EPS for g in gaps):
            out.append({"id": b.id, "name": b.name, "material": b.material})
    return out


@mcp.tool()
def wp_list_designs() -> list[dict]:
    """List design files (name, title)."""
    return [{"name": x["name"], "title": x["title"]} for x in store.list_designs()]


@mcp.tool()
def wp_get_design(name: str) -> dict:
    """The whole design: params (value + expression), materials, resolved parts, joints,
    hardware, overall bounds and issues. Also returns `raw`, the file as written."""
    d = store.load(name)
    return {**d.to_dict(geometry=False), "raw": d.raw}


@mcp.tool()
def wp_get_selection() -> dict:
    """What the human has selected in the viewer (click a part). Use for 'this' / 'that bracket'."""
    sel = store.get_selection()
    if not sel.get("design") or not sel.get("parts"):
        return {**sel, "note": "nothing selected; ask the human to click the part"}
    d = store.load(sel["design"])
    sel["details"] = [d.part(pid).to_dict(geometry=False) for pid in sel["parts"] if pid in {p.id for p in d.parts}]
    return sel


@mcp.tool()
def wp_explain_part(name: str, part_id: str) -> dict:
    """Everything needed to explain one part: its role and notes, material, size, the
    joints and fasteners it takes part in, and the parts it touches."""
    d = store.load(name)
    p = d.part(part_id)
    return {
        "part": p.to_dict(geometry=False),
        "material": d.raw.get("materials", {}).get(p.material, {}),
        "component": d.components.get(p.component) if p.component else None,
        "spec": next(x for x in d.raw["parts"] if x.get("id") == p.source),
        "joints": d.joints_for(part_id),
        "touching": _touching(d, part_id),
        "mass_kg": round(cutlist.part_mass(p, d.raw.get("materials", {})), 2),
    }


@mcp.tool()
def wp_set_param(name: str, param: str, value: Any, label: str | None = None,
                 notes: str | None = None) -> dict:
    """Set (or add) a param. `value` is a number in mm or an expression over other params."""
    return _summary(store.set_param(name, param, value, label, notes))


@mcp.tool()
def wp_remove_param(name: str, param: str) -> dict:
    """Remove a param (refused if something still uses it)."""
    return _summary(store.remove_param(name, param))


@mcp.tool()
def wp_update_part(name: str, part_id: str, fields: dict) -> dict:
    """Merge fields into a part, e.g. {"size": ["base_w", 600, "ply"]} or {"role": "..."}.
    A field set to null is removed. Renaming `id` updates the joints that use it."""
    return _summary(store.update_part(name, part_id, fields))


@mcp.tool()
def wp_add_part(name: str, part: dict, after: str | None = None) -> dict:
    """Add a part: {id, name, group, material, shape?, leg?, size, at, role, notes?, mass_kg?}."""
    return _summary(store.add_part(name, part, after))


@mcp.tool()
def wp_move_part(name: str, part_id: str, delta: list[float]) -> dict:
    """Move a part (and all its copies) by [dx, dy, dz] mm. Expressions are kept
    ("post_x" becomes "post_x + 40")."""
    d = store.load(name)
    return _summary(store.move_part(name, d.part(part_id).source if part_id not in
                                    {x.get("id") for x in d.raw["parts"]} else part_id, delta))


@mcp.tool()
def wp_remove_part(name: str, part_id: str) -> dict:
    """Remove a part (and drop it from joints)."""
    return _summary(store.remove_part(name, part_id))


@mcp.tool()
def wp_set_joint(name: str, joint: dict) -> dict:
    """Add or replace a joint by id: {id, type, parts: [...], fasteners, notes}."""
    return _summary(store.set_joint(name, joint))


@mcp.tool()
def wp_remove_joint(name: str, joint_id: str) -> dict:
    """Remove a joint by id."""
    return _summary(store.remove_joint(name, joint_id))


@mcp.tool()
def wp_set_material(name: str, material_id: str, spec: dict) -> dict:
    """Add or replace a material. Sheet: {name, kind:"sheet", thickness, stock:[l,w], density}.
    Lumber: {name, kind:"lumber", section:[a,b], stock_length, density}.
    Hardware/reference: {name, kind, mass_kg?, notes?}. Density is kg/m3."""
    return _summary(store.set_material(name, material_id, spec))


@mcp.tool()
def wp_set_hardware(name: str, items: list[dict]) -> dict:
    """Replace the loose hardware list (screws, bolts, glue): [{item, qty, notes?}]."""
    return _summary(store.set_hardware(name, items))


@mcp.tool()
def wp_set_meta(name: str, title: str | None = None, description: str | None = None) -> dict:
    """Change the design's title or description."""
    return _summary(store.set_meta(name, title, description))


@mcp.tool()
def wp_create_design(name: str, title: str, description: str = "", copy_from: str | None = None) -> dict:
    """Create a new design file (name: lowercase, digits, - and _). copy_from clones another."""
    return _summary(store.create(name, title, description, copy_from, created_by="agent"))


@mcp.tool()
def wp_undo(name: str) -> dict:
    """Revert the last change to a design (repeatable)."""
    return _summary(store.undo(name))


@mcp.tool()
def wp_check(name: str) -> dict:
    """Issues (overlaps, wrong stock sizes, parts below the floor) plus the tip check:
    centre of gravity, how far it can lean before it tips, and the push at the top that
    tips it, in each direction."""
    d = store.load(name)
    return {"issues": d.issues, "stability": cutlist.stability(d)}


@mcp.tool()
def wp_cut_list(name: str) -> dict:
    """Parts list: cut list grouped by identical pieces, stock to buy, and hardware.
    `text` is ready to show the human."""
    d = store.load(name)
    return {"text": format_cutlist(d), **cutlist.cut_list(d)}


@mcp.tool()
def wp_catalog_search(q: str = "") -> list[dict]:
    """Search the catalog of bought products (IKEA furniture etc.) by words in the name,
    brand, article number or category. Empty q lists everything."""
    return catalog.search(q)


@mcp.tool()
def wp_catalog_get(item_id: str) -> dict:
    """Full catalog entry: published size (mm, W x D x H), loads, price, source URL, panel
    recipe, what is assumed, and construction notes. Also the generated panels."""
    it = catalog.get(item_id)
    return {**it, "panels": catalog.generate(it, {})}


@mcp.tool()
def wp_catalog_add(item: dict) -> dict:
    """Add or replace a catalog product. Use only numbers published by the maker.
    Required: id (e.g. "ikea-hemnes-..."), brand, name, size [W, D, H] mm, url, retrieved
    (YYYY-MM-DD), geometry. Optional: article, category, price {amount, currency}, load
    {per_shelf_kg, top_kg, ...}, package_kg / mass_kg, material, construction (how to
    fasten to it), assumed [what is not published], color.
    geometry: {"generator": "cube_grid", "cols", "rows", "panel"} (KALLAX-style),
    {"generator": "carcass", "panel", "back", "shelves", "partitions", "plinth"}
    (BILLY/BESTÅ-style), {"generator": "table", "top", "leg"} (top on 4 legs), or
    {"generator": "block"} (a solid box)."""
    return catalog.add(item)


@mcp.tool()
def wp_ikea_search(q: str) -> dict:
    """Live search of IKEA's shop (country from WOODPECKER_IKEA_COUNTRY, default ee) via its
    unofficial web endpoints. Returns article numbers, names, IKEA's size label (W x D x H),
    price, product URL, and `in_catalog` (local catalog id if already imported). Pass the
    article (or URL) to wp_ikea_import to use one in a design."""
    cc, lang = ikea.market()
    return {"market": f"{cc}/{lang}", "results": ikea.search(q)}


@mcp.tool()
def wp_ikea_import(ref: str) -> dict:
    """Import one IKEA product into the local catalog from its product page: published
    width/depth/height, load limits, package weights, materials, price and notes. ref is
    an article number ("202.758.14"), item number or product URL. Internal structure (panel
    thickness, shelves) is guessed by product type and listed in `assumed`; refine it with
    wp_catalog_add if the human measures. Products already in the catalog are kept as they are.
    Returns the catalog id to use as a part's `component`."""
    return ikea.import_product(ref)


@mcp.tool()
def wp_publish(name: str) -> dict:
    """Create or refresh the design's Magpie page now (drawings from 5 angles, shopping
    list, cut list, parameters, tip check). Returns the page link. Anything people wrote
    under the page's Notes heading is kept."""
    return magpie.publish(name)


@mcp.tool()
def wp_export_images(name: str, views: list[str] | None = None) -> dict:
    """Render PNG drawings of a design and save them under .woodpecker/exports/<name>/.
    views: any of 3d, 3d-back, front, side, top (default all). Front/side/top are flat
    scale views with overall dimensions. Returns the file paths (and the Magpie page link,
    where the same pictures are published)."""
    d = store.load(name)
    out_dir = store.STATE / "exports" / name
    out_dir.mkdir(parents=True, exist_ok=True)
    files = {}
    for v in views or list(render.VIEWS):
        if v not in render.VIEWS:
            raise DesignError(f"unknown view {v!r}; use {', '.join(render.VIEWS)}")
        f = out_dir / f"{name}-{v}.png"
        f.write_bytes(render.render(d, v))
        files[v] = str(f)
    return {"files": files, "page": magpie.info(name)}


def main():
    mcp.run()


if __name__ == "__main__":
    main()
